namespace Conundrum.Model
{
    /// <summary>
    /// Represents the settings for a reflector, including its mapping and name.
    /// </summary>
    public class ReflectorSetting
    {
        /// <summary>
        /// Gets or sets the mapping configuration for the reflector.
        /// </summary>
        public string Map { get; set; }

        /// <summary>
        /// Gets or sets the name of the reflector.
        /// </summary>
        public string Name { get; set; }
    }
}
